// Builds everything that depends on the theme palettes, from app/globals.css:
//   lib/brand-icon-colors.ts      the mark's colours per theme (hex)
//   app/brand-icon.css            the same colours as CSS variables, for the inline mark
//   public/icons/theme/*.png      Home Screen / install icons per theme
//   public/icons/app-*.png, apple-touch-icon.png, app/favicon.ico   the default (Spruce) set
// Re-run after changing a theme's colours or lib/brand-icon.ts:  npx tsx scripts/make-brand-icons.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import sharp from "sharp"
import { THEMES } from "../lib/themes"
import { brandSvg, type BrandColors } from "../lib/brand-icon"

const css = readFileSync("app/globals.css", "utf8")

/** The declarations of the first block whose selector is exactly `selector` and that sets --primary. */
function blockFor(selector: string): string {
  const re = new RegExp(`(^|\\n)${selector.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}\\s*\\{([^}]*)\\}`, "g")
  for (const m of css.matchAll(re)) if (m[2].includes("--primary:")) return m[2]
  throw new Error(`no ${selector} block with --primary in globals.css`)
}

const selectorOf = (id: string) => (id === "light" ? ":root" : id === "dark" ? ".dark" : `[data-theme="${id}"]`)

function varOf(block: string, name: string): string {
  const m = block.match(new RegExp(`${name}:\\s*(oklch\\([^)]*\\))`))
  if (!m) throw new Error(`${name} is not an oklch() value`)
  return m[1]
}

// oklch -> sRGB hex (Björn Ottosson's matrices), clipped to gamut.
function oklchToHex(value: string): string {
  const nums = value.match(/oklch\(\s*([\d.]+)\s+([\d.]+)\s+([\d.]+)/)
  if (!nums) throw new Error(`cannot parse ${value}`)
  const [L, C, h] = [Number(nums[1]), Number(nums[2]), (Number(nums[3]) * Math.PI) / 180]
  const a = C * Math.cos(h)
  const b = C * Math.sin(h)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
  const enc = (x: number) => {
    const v = Math.min(1, Math.max(0, x))
    return Math.round((v <= 0.0031308 ? 12.92 * v : 1.055 * v ** (1 / 2.4) - 0.055) * 255)
  }
  return "#" + lin.map((x) => enc(x).toString(16).padStart(2, "0")).join("")
}

const lum = (hex: string) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4))
  return 0.2126 * r + 0.7152 * g + 0.0722 * b
}
const contrast = (a: string, b: string) => {
  const [hi, lo] = [lum(a), lum(b)].sort((x, y) => y - x)
  return (hi + 0.05) / (lo + 0.05)
}
const mix = (a: string, b: string, t: number) =>
  "#" + [1, 3, 5].map((i) => Math.round(parseInt(a.slice(i, i + 2), 16) * (1 - t) + parseInt(b.slice(i, i + 2), 16) * t).toString(16).padStart(2, "0")).join("")

/** The preferred accent if it stands out from the tile, else the theme colour that stands out most, else a blend of the glyph colour. */
function accent(preferred: string, pool: string[], tile: string, glyph: string, avoid: string[], min: number): string {
  if (contrast(preferred, tile) >= min) return preferred
  const best = pool
    .filter((c) => !avoid.includes(c))
    .sort((x, y) => contrast(y, tile) - contrast(x, tile))[0]
  if (best && contrast(best, tile) >= min) return best
  return mix(tile, glyph, 0.6)
}

const colors: Record<string, BrandColors> = {}
for (const t of THEMES) {
  const block = blockFor(selectorOf(t.id))
  const tile = oklchToHex(varOf(block, "--primary"))
  const glyph = oklchToHex(varOf(block, "--primary-foreground"))
  const charts = [1, 2, 3, 4, 5].map((n) => oklchToHex(varOf(block, `--chart-${n}`)))
  // Chart colours that match the tile or the roof would vanish into them.
  const check = accent(charts[2], charts, tile, glyph, [tile, glyph], 2.4)
  const hill = accent(charts[3], charts, tile, glyph, [tile, glyph, check], 1.8)
  colors[t.id] = { tile, glyph, check, hill, background: oklchToHex(varOf(block, "--background")) }
}

writeFileSync(
  "lib/brand-icon-colors.ts",
  `// Generated by scripts/make-brand-icons.ts from the palettes in app/globals.css. Do not edit.\nimport type { BrandColors } from "@/lib/brand-icon"\n\nexport const BRAND_COLORS: Record<string, BrandColors> = ${JSON.stringify(colors, null, 2)}\n`
)

// The same colours as CSS variables, so the inline mark follows the theme with no script.
writeFileSync(
  "app/brand-icon.css",
  [
    "/* Generated by scripts/make-brand-icons.ts from the palettes in globals.css. Do not edit. */",
    ...THEMES.map((t) => {
      const c = colors[t.id]
      return `${selectorOf(t.id)} { --brand-tile: ${c.tile}; --brand-glyph: ${c.glyph}; --brand-check: ${c.check}; --brand-hill: ${c.hill}; }`
    }),
    "",
  ].join("\n")
)

const png = (svg: string, size: number) => sharp(Buffer.from(svg), { density: 384 }).resize(size, size).png().toBuffer()

// Maskable and Home Screen icons are squares the platform masks itself; the mark sits inside the safe zone.
async function set(id: string, dir: string, names: { any192: string; any512: string; maskable: string; apple: string }) {
  const c = colors[id]
  writeFileSync(`${dir}/${names.any192}`, await png(brandSvg(c), 192))
  writeFileSync(`${dir}/${names.any512}`, await png(brandSvg(c), 512))
  writeFileSync(`${dir}/${names.maskable}`, await png(brandSvg(c, { shape: "square", scale: 0.78 }), 512))
  writeFileSync(`${dir}/${names.apple}`, await png(brandSvg(c, { shape: "square", scale: 0.9 }), 180))
}

async function main() {
  mkdirSync("public/icons/theme", { recursive: true })
  for (const t of THEMES) {
    await set(t.id, "public/icons/theme", {
      any192: `${t.id}-192.png`, any512: `${t.id}-512.png`, maskable: `${t.id}-maskable.png`, apple: `${t.id}-apple.png`,
    })
  }
  // The default set, used before a theme is chosen and as the fallback.
  await set("light", "public/icons", { any192: "app-192.png", any512: "app-512.png", maskable: "app-maskable-512.png", apple: "apple-touch-icon.png" })

  // favicon.ico: PNG images inside an ICO container.
  const sizes = [16, 32, 48, 64]
  const images = await Promise.all(sizes.map((s) => png(brandSvg(colors.light), s)))
  const header = Buffer.alloc(6)
  header.writeUInt16LE(1, 2)
  header.writeUInt16LE(images.length, 4)
  let offset = 6 + images.length * 16
  const entries = images.map((img, i) => {
    const e = Buffer.alloc(16)
    e.writeUInt8(sizes[i] === 256 ? 0 : sizes[i], 0)
    e.writeUInt8(sizes[i] === 256 ? 0 : sizes[i], 1)
    e.writeUInt16LE(1, 4)
    e.writeUInt16LE(32, 6)
    e.writeUInt32LE(img.length, 8)
    e.writeUInt32LE(offset, 12)
    offset += img.length
    return e
  })
  writeFileSync("app/favicon.ico", Buffer.concat([header, ...entries, ...images]))

  console.log(`Wrote colours and icons for ${THEMES.length} themes.`)
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
